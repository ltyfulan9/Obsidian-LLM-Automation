"""Date and topic views plus maps, all derived from the same catalog."""

from __future__ import annotations

import json
import re
from collections import defaultdict
from pathlib import Path
from urllib.parse import quote

from .common import digest, slug
from .scope import sync_scope
from .projection_store import commit, recover

MARKER = "<!-- Generated by knowledge; put handwritten notes in Notes/. -->\n\n"


def label(text: str) -> str:
    return re.sub(r"[\r\n\[\]<>|`]+", " ", text).strip()


def link(title: str, path: str) -> str:
    return f"[{label(title)}]({quote(path, safe='/.-')})"


def card_path(row: dict) -> str:
    return f"Sources/{row['document']['id']}.md"


def items(values: list[str]) -> str:
    return "\n".join("- " + value.replace("\n", "\n  ") for value in values) or "- 暂无记录。"


def projections(rows: list[dict], config: dict, personal: dict | None = None) -> dict[str, str]:
    from .personal_render import daily_blocks, projections as personal_projections
    personal = personal or {}
    daily = daily_blocks(personal)
    files = {}
    scope = sync_scope(config)
    engine_label = "本地摘录与关键词分类" if scope["summary_engine"] == "extract" else scope["summary_engine"] + " AI 语义归纳"
    scope_page = "# 这个知识库同步什么\n\n"
    scope_page += f"整理方式：**{engine_label}**。以下范围由当前配置生成。\n\n"
    scope_page += "## 已配置来源\n\n| 来源别名 | 类型 | 日期范围 |\n| --- | --- | --- |\n"
    for source in scope["sources"]:
        scope_page += f"| {label(source['name'])} | {source['kind']} | {source['since'] + ' 起' if source['since'] else '全部匹配日期'} |\n"
    if not scope["sources"]:
        scope_page += "\n尚未添加资料来源。\n"
    scope_page += "\n## 会同步到私有 GitHub\n\n"
    scope_page += "- 笔记与 AI 对话内容小结：来源卡片、日期日记、主题 Wiki。\n"
    scope_page += "- 要点、已明确的决定与待解决问题，保留来源和核实边界。\n"
    scope_page += "- 每日回填、本人确认的承诺及变更原因、实际结果与带依据的规则复盘。\n"
    scope_page += "- 时间线、思维导图、关系图、Obsidian Canvas，以及手写 `Notes/`。\n"
    scope_page += "- 仅执行 `publish` 或 `sync --push` 时发送；普通 `sync` 只更新本地。\n"
    scope_page += ("- 已启用 `Archive/` 规范化正文归档；正文会随生成文件参与私有发布。\n" if scope["raw_archive"]
                   else "- 完整对话正文归档未启用；默认发布摘要，正文仅保存在忽略的本地数据库。\n")
    scope_page += "\n## 保留在本机\n\n- `.knowledge/` 中的来源路径、配置、正文数据库、锁和运行状态。\n"
    scope_page += "\n## 不采集为知识正文\n\n- API Key、登录配置、隐藏推理和工具输出。\n"
    scope_page += "- Magpie 的加密配置备份由 Magpie 自己同步，本工具不会读取或解密。\n"
    scope_page += "\n只会处理明确配置且匹配筛选的本机资料；未知云端对话不会自动出现。摘要仍可能包含私人信息，目标必须保持私有。\n"
    files["Sync.md"] = scope_page
    by_day = defaultdict(list)
    by_topic = defaultdict(list)
    by_month = defaultdict(list)
    for row in rows:
        document, summary = row["document"], row["summary"]
        by_day[document["day"]].append(row)
        for topic in summary["topics"]:
            by_topic[topic].append(row)
        # Method is recorded in the summary rather than inferred from today's config.
        method = "本地摘录，未经语义归纳" if summary.get("method") == "extract" else "AI 整理，请核对来源"
        source_status = "来源可访问" if row["available"] else "来源已删除、改名或不再匹配筛选；保留历史记录"
        page = f"# {label(summary['title'])}\n\n"
        page += f"- 日期：{document['day']}\n- 来源类型：{document['kind']}\n- 来源：`{document['source']}/{document['origin']}`\n"
        page += f"- 状态：{source_status}\n- 整理方式：{method}\n"
        page += "- 主题：" + "、".join(link(topic, f"../Wiki/{slug(topic)}.md") for topic in summary["topics"]) + "\n\n"
        page += f"## 摘要\n\n{summary['summary']}\n\n## 要点\n\n{items(summary['key_points'])}\n\n"
        page += f"## 明确决策\n\n{items(summary['decisions'])}\n\n## 待解决问题\n\n{items(summary['questions'])}\n\n"
        page += link("回到日期页", f"../Daily/{document['day']}.md") + " · " + link("知识库首页", "../Home.md") + "\n"
        files[card_path(row)] = page
        if config.get("include_raw", False):
            files[f"Archive/{document['id']}.md"] = f"# 规范化来源正文\n\n{document['text']}\n"

    for day in daily:
        by_day.setdefault(day, [])
    for day in sorted(by_day, reverse=True):
        entries = by_day[day]
        by_month[day[:7]].append(day)
        page = f"# {day} · 知识日记\n\n" + link("全部日期", "../Timeline.md") + " · " + link("知识库首页", "../Home.md") + "\n\n"
        page += daily.get(day, "")
        for row in entries:
            summary = row["summary"]
            page += "## " + link(summary["title"], "../" + card_path(row)) + "\n\n" + summary["summary"] + "\n\n"
            if summary["decisions"]:
                page += "### 决策\n\n" + items(summary["decisions"]) + "\n\n"
            if summary["questions"]:
                page += "### AI 整理的待解决问题（未经承诺确认）\n\n" + items(summary["questions"]) + "\n\n"
        files[f"Daily/{day}.md"] = page

    for topic in sorted(by_topic):
        entries = by_topic[topic]
        page = f"# {label(topic)}\n\n" + link("知识库首页", "../Home.md") + "\n\n"
        page += "按时间聚合的主题证据。各来源结论可能处于不同阶段；这里保留差异，不自动将计划合并为事实。\n\n"
        decisions = list(dict.fromkeys(value for row in entries for value in row["summary"]["decisions"]))
        questions = list(dict.fromkeys(value for row in entries for value in row["summary"]["questions"]))
        page += "## 已记录的决策\n\n" + items(decisions) + "\n\n## 尚待解决\n\n" + items(questions) + "\n\n## 来源与时间\n\n"
        for row in entries:
            page += "### " + row["document"]["day"] + " · " + link(row["summary"]["title"], "../" + card_path(row)) + "\n\n"
            page += row["summary"]["summary"] + "\n\n"
        files[f"Wiki/{slug(topic)}.md"] = page

    files["Timeline.md"] = "# 知识时间线\n\n" + "\n\n".join(
        "## " + month + "\n\n" + "\n".join("- " + link(day, f"Daily/{day}.md") + f" · {len(by_day[day])} 份资料" for day in days)
        for month, days in sorted(by_month.items(), reverse=True)) + "\n"
    files["Home.md"] = (
        "# 个人知识库\n\n"
        f"共 **{len(rows)}** 份日期资料、**{len(by_topic)}** 个主题、**{len(by_day)}** 个日期。\n\n"
        + link("时间线", "Timeline.md") + " · " + link("主题导图", "Maps/Mindmap.md") + " · "
        + link("关系图", "Maps/Graph.md") + " · " + link("Obsidian Canvas", "Maps/Knowledge.canvas") + "\n\n"
        + link("查看同步范围", "Sync.md") + "\n\n"
        + link("承诺与实际结果", "Tasks.md") + " · " + link("行为复盘与每周回看", "Review.md") + "\n\n"
        "每天采集资料，再回填完成事项、阻碍和教训；确认承诺后记录实际结果，用有日期依据的复盘检查改进。\n\n"
        "## 主题 Wiki\n\n" + ("\n".join("- " + link(topic, f"Wiki/{slug(topic)}.md") + f" · {len(entries)} 份来源" for topic, entries in sorted(by_topic.items())) or "尚未导入资料。")
        + "\n\n## 最近日记\n\n" + "\n".join("- " + link(day, f"Daily/{day}.md") for day in sorted(by_day, reverse=True)[:14])
        + "\n\n## 手写知识\n\n在 `Notes/` 保存长期笔记，生成器不会改写此目录。\n"
    )

    limit = max(10, min(int(config.get("graph_max_documents", 120)), 500))
    graph_rows = rows[:limit]
    graph_topics = sorted({topic for row in graph_rows for topic in row["summary"]["topics"]})
    topic_ids = {topic: "t" + digest(topic)[:12] for topic in graph_topics}
    mindmap = ["# 主题导图", "", f"导图展示最近 {len(graph_rows)} 份资料；完整内容见 Wiki 和时间线。", "", "```mermaid", "mindmap", "  root((个人知识库))"]
    graph = ["# 知识关系图", "", "主题与来源的关联来自摘要主题标签，不能单独证明因果关系。", "", "```mermaid", "graph LR"]
    nodes, edges = [], []
    for index, topic in enumerate(graph_topics):
        topic_id = topic_ids[topic]
        safe = label(topic).replace('"', "'").replace("(", "（").replace(")", "）")
        mindmap.append(f'    {topic_id}["{safe}"]')
        entries = [row for row in graph_rows if topic in row["summary"]["topics"]]
        for row in entries[:8]:
            title = label(row["summary"]["title"]).replace('"', "'").replace("(", "（").replace(")", "）")[:60]
            mindmap.append(f'      d{row["document"]["id"]}{topic_id}["{row["document"]["day"]} {title}"]')
        graph.append(f'  {topic_id}["{safe}"]')
        nodes.append({"id": topic_id, "type": "file", "file": f"Wiki/{slug(topic)}.md", "x": 0, "y": index * 180, "width": 280, "height": 100})
    for index, row in enumerate(graph_rows):
        node_id = "d" + row["document"]["id"]
        title = label(row["summary"]["title"]).replace('"', "'")[:60]
        graph.append(f'  {node_id}["{row["document"]["day"]} {title}"]')
        nodes.append({"id": node_id, "type": "file", "file": card_path(row), "x": 520, "y": index * 150, "width": 360, "height": 110})
        for topic in row["summary"]["topics"]:
            topic_id = topic_ids[topic]
            graph.append(f"  {topic_id} --> {node_id}")
            edges.append({"id": digest(topic_id + node_id)[:16], "fromNode": topic_id, "fromSide": "right", "toNode": node_id, "toSide": "left"})
    files["Maps/Mindmap.md"] = "\n".join(mindmap + ["```", ""])
    files["Maps/Graph.md"] = "\n".join(graph + ["```", ""])
    files["Maps/Knowledge.canvas"] = json.dumps({"nodes": nodes, "edges": edges}, ensure_ascii=False, indent=2) + "\n"
    files.update(personal_projections(personal, config))
    return files


def build(root: Path, rows: list[dict], config: dict, personal: dict | None = None) -> int:
    recover(root)
    generated = projections(rows, config, personal)
    contents = {}
    for relative, content in generated.items():
        content = content.rstrip() + "\n"
        contents[relative] = content if relative.endswith(".canvas") else MARKER + content
    return commit(root, contents)
